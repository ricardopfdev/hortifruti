CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(11) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    senha_acesso VARCHAR(50) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'FAMILIA',
    familia_id BIGINT NOT NULL UNIQUE REFERENCES familias(id) ON DELETE CASCADE,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    criado_em TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_usuarios_familia_id ON usuarios(familia_id);
